-- REALGX 4K — Supabase setup
-- Public visitors can read; only authenticated users whose app_metadata.role
-- is exactly "admin" can insert or delete. Never grant public write access.

create table if not exists public.wallpapers (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) > 0),
  category text not null check (length(trim(category)) > 0),
  preview_url text not null,
  full_url text not null,
  created_at timestamptz not null default now()
);

alter table public.wallpapers enable row level security;
grant select on table public.wallpapers to anon, authenticated;
grant insert, delete on table public.wallpapers to authenticated;
grant usage, select on sequence public.wallpapers_id_seq to authenticated;

drop policy if exists "Wallpapers are publicly readable" on public.wallpapers;
create policy "Wallpapers are publicly readable"
on public.wallpapers for select to anon, authenticated using (true);

drop policy if exists "Only admins can insert wallpapers" on public.wallpapers;
create policy "Only admins can insert wallpapers"
on public.wallpapers for insert to authenticated
with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Only admins can delete wallpapers" on public.wallpapers;
create policy "Only admins can delete wallpapers"
on public.wallpapers for delete to authenticated
using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create index if not exists wallpapers_created_at_idx
on public.wallpapers (created_at desc);
