-- REALGX 4K — Supabase database setup
-- Reproduces the current application schema and access model.
--
-- IMPORTANT:
-- 1. Run this in the Supabase SQL Editor for a NEW project.
-- 2. Existing wallpaper rows are not deleted.
-- 3. Shared layout editing is intentionally public in the current app.
--    Anyone can overwrite a saved layout; see the README security note.

create table if not exists public.wallpapers (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) > 0),
  category text not null check (length(trim(category)) > 0),
  preview_url text not null,
  full_url text not null,
  created_at timestamptz not null default now(),
  description text not null default '',
  layout_settings jsonb not null default '{}'::jsonb
);

-- Keep this setup compatible with an earlier REALGX wallpapers table.
alter table public.wallpapers
  add column if not exists description text not null default '';

alter table public.wallpapers
  add column if not exists layout_settings jsonb not null default '{}'::jsonb;

create table if not exists public.wallpaper_layouts (
  wallpaper_id text primary key,
  settings jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create index if not exists wallpapers_created_at_idx
  on public.wallpapers (created_at desc);

alter table public.wallpapers enable row level security;
alter table public.wallpaper_layouts enable row level security;

-- Least-privilege table grants used by the frontend.
grant select on table public.wallpapers to anon, authenticated;
grant insert, update, delete on table public.wallpapers to authenticated;
grant usage, select on sequence public.wallpapers_id_seq to authenticated;

-- Public visitors can read and save shared layout adjustments.
grant select, insert, update on table public.wallpaper_layouts to anon, authenticated;

-- Wallpapers: public read; authenticated admin-only publishing and maintenance.
drop policy if exists "Wallpapers are publicly readable" on public.wallpapers;
create policy "Wallpapers are publicly readable"
  on public.wallpapers
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Only admins can insert wallpapers" on public.wallpapers;
create policy "Only admins can insert wallpapers"
  on public.wallpapers
  for insert
  to authenticated
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Only admins can update wallpaper layouts" on public.wallpapers;
create policy "Only admins can update wallpaper layouts"
  on public.wallpapers
  for update
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "Only admins can delete wallpapers" on public.wallpapers;
create policy "Only admins can delete wallpapers"
  on public.wallpapers
  for delete
  to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- Shared layouts: intentionally writable by visitors for the current
-- no-login editing experience. Add moderation/authentication before
-- using this policy for a high-traffic or abuse-sensitive service.
drop policy if exists "Anyone can read shared wallpaper layouts" on public.wallpaper_layouts;
create policy "Anyone can read shared wallpaper layouts"
  on public.wallpaper_layouts
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can create shared wallpaper layouts" on public.wallpaper_layouts;
create policy "Anyone can create shared wallpaper layouts"
  on public.wallpaper_layouts
  for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Anyone can update shared wallpaper layouts" on public.wallpaper_layouts;
create policy "Anyone can update shared wallpaper layouts"
  on public.wallpaper_layouts
  for update
  to anon, authenticated
  using (true)
  with check (true);
